'use strict';
const fs=require('fs'),path=require('path'),os=require('os'),assert=require('assert/strict');
const {createSettings}=require('../server/settings');
let count=0;const pass=s=>{count++;console.log('PASS '+s);};
(async()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'overleaf-settings-test-')),settings=createSettings({directory:path.join(root,'config')});
 assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:3000});assert(!fs.existsSync(settings.file));
 pass('a missing settings file defaults to auto mode with a 3000 ms debounce');
 const previousEnv=process.env.OVERLEAF_SYNC_DELAY_MS;
 process.env.OVERLEAF_SYNC_DELAY_MS='2500';assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:2500});
 process.env.OVERLEAF_SYNC_DELAY_MS='999';assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:3000});
 process.env.OVERLEAF_SYNC_DELAY_MS='60001';assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:3000});
 process.env.OVERLEAF_SYNC_DELAY_MS='2500.5';assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:3000});
 process.env.OVERLEAF_SYNC_DELAY_MS='abc';assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:3000});
 if(previousEnv===undefined)delete process.env.OVERLEAF_SYNC_DELAY_MS;else process.env.OVERLEAF_SYNC_DELAY_MS=previousEnv;
 pass('a valid OVERLEAF_SYNC_DELAY_MS overrides the default while invalid values are ignored');
 assert.deepEqual(settings.update({syncMode:'manual'}),{syncMode:'manual',syncDelayMs:3000});
 assert.deepEqual(settings.update({syncDelayMs:4500}),{syncMode:'manual',syncDelayMs:4500});
 assert.deepEqual(settings.read(),{syncMode:'manual',syncDelayMs:4500});
 assert.deepEqual(JSON.parse(fs.readFileSync(settings.file,'utf8')),{syncMode:'manual',syncDelayMs:4500});
 pass('update merges patches, writes the full object and reads it back');
 process.env.OVERLEAF_SYNC_DELAY_MS='2500';
 assert.deepEqual(settings.update({syncDelayMs:5000}),{syncMode:'manual',syncDelayMs:5000});
 assert.deepEqual(settings.read(),{syncMode:'manual',syncDelayMs:5000});
 if(previousEnv===undefined)delete process.env.OVERLEAF_SYNC_DELAY_MS;else process.env.OVERLEAF_SYNC_DELAY_MS=previousEnv;
 pass('values written to the settings file take priority over the environment default');
 assert.throws(()=>settings.update({syncMode:'fast'}),/syncMode/);
 assert.throws(()=>settings.update({syncDelayMs:999}),/syncDelayMs/);
 assert.throws(()=>settings.update({syncDelayMs:61000}),/syncDelayMs/);
 assert.throws(()=>settings.update({syncDelayMs:2500.5}),/syncDelayMs/);
 assert.throws(()=>settings.update({syncDelayMs:'2500'}),/syncDelayMs/);
 assert.deepEqual(settings.read(),{syncMode:'manual',syncDelayMs:5000});
 pass('invalid patches throw Chinese errors and leave the stored settings unchanged');
 assert.equal(settings.file,path.join(root,'config','settings.json'));
 assert.deepEqual(fs.readdirSync(path.join(root,'config')),['settings.json']);
 assert.equal(fs.statSync(settings.file).mode&0o777,0o600);
 assert.equal(fs.statSync(path.join(root,'config')).mode&0o777,0o700);
 pass('settings are written atomically as a private settings.json without leftover temp files');
 fs.writeFileSync(settings.file,'{ corrupted json');
 assert.deepEqual(settings.read(),{syncMode:'auto',syncDelayMs:3000});
 assert.deepEqual(settings.update({syncMode:'auto'}),{syncMode:'auto',syncDelayMs:3000});
 assert.deepEqual(JSON.parse(fs.readFileSync(settings.file,'utf8')),{syncMode:'auto',syncDelayMs:3000});
 pass('a corrupted file falls back to defaults and the next update repairs it');
 console.log('ALL '+count+' SETTINGS TESTS PASSED');
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
