'use strict';
const fs=require('fs'),path=require('path'),os=require('os'),assert=require('assert/strict');
const createPreview=require('../server/preview');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'overleaf-preview-perf-'));
let checks=0;const pass=n=>{checks++;console.log('PASS '+n);};
const CACHE=path.join(root,'cache'),dir=path.join(CACHE,'.previews');
const getEntry=async()=>({storageId:'f'.repeat(24),projectId:null,type:'local',name:'Preview fixture'});
const workspace={snapshot:async()=>({files:[],revision:'local',sourceHash:'s',dirty:false,localPath:path.join(root,'paper')})};
const run=async()=>({ok:true,out:'',err:''});
const preview=createPreview({CACHE_ROOT:CACHE,getEntry,workspace,run,compilerHelper:false});
const hex=i=>i.toString(16).padStart(4,'0');
const buildId=i=>'f'.repeat(24)+'-'+'b'.repeat(32)+hex(i);
for(let i=0;i<120;i++){
 const id=buildId(i);
 fs.mkdirSync(path.join(dir,id));
 fs.writeFileSync(path.join(dir,id,'status.json'),JSON.stringify({buildId:id,projectKey:i===119?'p1':'other',startedAt:new Date(2026,0,1,0,i,0).toISOString(),status:'ready',pages:2,name:'Job '+i}));
}
fs.mkdirSync(path.join(dir,'not-a-build'));
const realRead=fs.readFileSync;let reads=0;
async function countStatusReads(fn){reads=0;fs.readFileSync=function(file,...rest){if(String(file).startsWith(dir+path.sep))reads++;return realRead.call(fs,file,...rest);};try{return await fn();}finally{fs.readFileSync=realRead;}}
(async()=>{
 const cold=await countStatusReads(()=>Promise.resolve(preview.latest('p1')));
 assert.equal(cold.buildId,buildId(119));
 assert.equal(reads,120);
 pass('cold latest-build lookup reads every saved build status');
 const warm=await countStatusReads(()=>Promise.resolve(preview.latest('p1')));
 assert.equal(warm.buildId,buildId(119));
 assert.equal(reads,0);
 pass('repeated latest-build lookup revalidates by stat and reads no status files');
 const newest=path.join(dir,buildId(119),'status.json'),tmp=newest+'.tmp';
 fs.writeFileSync(tmp,JSON.stringify({buildId:buildId(119),projectKey:'p1',startedAt:new Date(2026,0,2,0,0,0).toISOString(),status:'building',pages:2,name:'Job 119'}));
 fs.renameSync(tmp,newest);
 const externallyEdited=await countStatusReads(()=>Promise.resolve(preview.latest('p1')));
 assert.equal(externallyEdited.buildId,buildId(119));
 assert.equal(externallyEdited.status,'failed');
 assert(externallyEdited.error.includes('中断'));
 assert.equal(reads,1);
 pass('an externally replaced build status is re-read and an interrupted build is reported as failed');
 const oldest=path.join(dir,buildId(0));
 fs.rmSync(oldest,{recursive:true});
 const afterDelete=await countStatusReads(()=>Promise.resolve(preview.latest('p1')));
 assert.equal(afterDelete.buildId,buildId(119));
 pass('deleted build directories disappear from the lookup');
 const middle=path.join(dir,buildId(60),'status.json'),tmp2=middle+'.tmp';
 fs.writeFileSync(tmp2,JSON.stringify({buildId:buildId(60),projectKey:'p1',startedAt:new Date(2026,0,3,0,0,0).toISOString(),status:'ready',pages:3,name:'Job 60 promoted'}));
 fs.renameSync(tmp2,middle);
 const promoted=await countStatusReads(()=>Promise.resolve(preview.latest('p1')));
 assert.equal(promoted.buildId,buildId(60));
 assert.equal(promoted.pages,3);
 pass('a cached older build whose status changes on disk is revalidated and can become the latest');
 const midStat=fs.statSync(middle);
 fs.writeFileSync(middle,JSON.stringify({buildId:buildId(60),projectKey:'p1',startedAt:new Date(2026,0,3,0,0,0).toISOString(),status:'ready',pages:4,name:'Job 60 promoted'}));
 fs.utimesSync(middle,midStat.atime,midStat.mtime);
 const restored=await countStatusReads(()=>Promise.resolve(preview.latest('p1')));
 assert.equal(restored.buildId,buildId(60));
 assert.equal(restored.pages,4);
 assert.equal(reads,1);
 pass('a same-size status rewrite with restored mtime still revalidates through ctime');
 fs.writeFileSync('/tmp/overleaf-editor-v060/perf-preview-results.json',JSON.stringify({passed:true,checks,fixtureGenerated:true},null,2));
 console.log('ALL '+checks+' PERFORMANCE PREVIEW TESTS PASSED');
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
